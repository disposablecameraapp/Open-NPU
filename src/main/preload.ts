const invoke = (c: string, ...a: unknown[]) => ipcRenderer.invoke(c, ...a);
const on = <T>(channel: string, cb: (v: T) => void) => {
  const l = (_: unknown, v: T) => cb(v);
  ipcRenderer.on(channel, l);
  return () => ipcRenderer.removeListener(channel, l);
};

