// Builds src/core/page/vendor.generated.ts from the animation libraries in node_modules (all MIT):
//   AOS (scroll reveals), animate.css (entrances, a subset), countUp.js (counting figures).
// tsParticles was tried for the particles and drew nothing in a plain test page, so the particles are a small canvas of our own (page/css.ts).
// Run `node scripts/vendor-anim.js` after changing a version. The output is committed: the app needs no network and no node_modules at run time.
const fs = require("fs"), path = require("path");
const nm = (...p) => path.join(__dirname, "..", "node_modules", ...p);
const read = (...p) => fs.readFileSync(nm(...p), "utf8");

// the rules of animate.css that the page uses: the base, the delays and speeds, and a short list of animations
const WANTED = ["fadeIn", "fadeInDown", "fadeInUp", "fadeInLeft", "fadeInRight", "zoomIn", "bounceIn", "pulse", "heartBeat", "headShake", "tada", "flipInX", "slideInUp", "slideInDown"];
function topRules(css) {
  const out = []; let depth = 0, start = 0;
  css = css.replace(/@charset "UTF-8";/, "").replace(/\/\*[\s\S]*?\*\//g, "");
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") { depth--; if (depth === 0) { out.push(css.slice(start, i + 1)); start = i + 1; } }
  }
  return out;
}
const rules = topRules(read("animate.css", "animate.min.css")).filter((r) => {
  const head = r.slice(0, r.indexOf("{"));
  const name = /^@(?:-webkit-)?keyframes\s+(\w+)/.exec(head)?.[1] ?? /^\.animate__(\w[\w-]*)$/.exec(head.trim())?.[1];
  if (name) return WANTED.includes(name) || /^(animated|infinite|delay-\dsundefined|delay-\ds|repeat-\d|slow|slower|fast|faster)$/.test(name);
  return /^:root|^@media/.test(head.trim()) || /\.animate__animated/.test(head);
}).map((r) => r.trim());
const animateCss = rules.join("\n");

const licenses = [["AOS", "aos"], ["animate.css", "animate.css"], ["countUp.js", "countup.js"]].map(([label, pkg]) => {
  const f = ["LICENSE", "LICENSE.md", "license"].find((n) => fs.existsSync(nm(pkg, n)));
  return `=== ${label} ===\n${f ? read(pkg, f).trim() : "MIT License"}`;
}).join("\n\n");

const out = `// GENERATED by scripts/vendor-anim.js from node_modules (AOS, animate.css, countUp.js: all MIT). Do not edit.
export const AOS_JS = ${JSON.stringify(read("aos", "dist", "aos.js"))};
export const AOS_CSS = ${JSON.stringify(read("aos", "dist", "aos.css").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, " "))};
export const ANIMATE_CSS = ${JSON.stringify(animateCss)};
export const COUNTUP_JS = ${JSON.stringify(read("countup.js", "dist", "countUp.umd.js"))};
export const VENDOR_LICENSES = ${JSON.stringify(licenses)};
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "core", "page", "vendor.generated.ts"), out);
console.log("vendor.generated.ts", Math.round(out.length / 1024) + " KB", "animate.css rules:", rules.length);
